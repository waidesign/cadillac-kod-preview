    model = 'CT5';
    bodyStyle = '4-Door Luxury Sport Sedan';
    engine = '3.0L Twin-Turbo V6 (335 hp, 405 lb-ft)';
    transmission = '10-Speed Automatic with Paddle Shifters';
    baseMsrp = 47295;
